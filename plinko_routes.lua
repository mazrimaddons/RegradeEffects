function Plinko.sample(route, progress)
    if progress >= 1 then return route.restX, route.restY end

    local time = math.max(0, progress) * route.durationMs / 1000
    local segments = route.segments
    local first, last = 1, #segments
    while first < last do
        local middle = math.floor((first + last + 1) / 2)
        if segments[middle][1] <= time then first = middle else last = middle - 1 end
    end

    local origin = segments[first]
    local age = time - origin[1]
    local x, y = origin[2] + origin[4] * age, origin[3] + origin[5] * age
    if origin[6] then
        x = x + .5 * origin[6] * age * age
    else
        y = y + HALF_GRAVITY * age * age
    end
    return x, y
end

